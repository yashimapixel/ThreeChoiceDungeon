def res(rid):
    eid, k, b = rid.rsplit('_', 2)
    return EV[eid]['c'][int(k)][b]


def set_text(obj, key, old, new, label):
    if obj.get(key) == new:
        return
    assert obj.get(key) == old, '%s: unexpected text %r' % (label, obj.get(key))
    obj[key] = new
    done.append(label)


def rtext(rid, old, new):
    set_text(res(rid), 'd', old, new, rid)


def ctext(eid, k, old, new):
    set_text(EV[eid]['c'][k], 't', old, new, '%s choice %d' % (eid, k + 1))


def etext(eid, old, new):
    set_text(EV[eid], 'd', old, new, eid)


def set_key(obj, key, value, label):
    if obj.get(key) != value:
        obj[key] = value
        done.append(label)


